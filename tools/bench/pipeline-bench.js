function vnoise(x, y, p, s) { const xi = Math.floor(x), yi = Math.floor(y), fx = x - xi, fy = y - yi, w = v => v * v * (3 - 2 * v), m = (a, n) => ((a % n) + n) % n;
  const a = hash(m(xi, p), m(yi, p), s), b = hash(m(xi + 1, p), m(yi, p), s), c = hash(m(xi, p), m(yi + 1, p), s), d = hash(m(xi + 1, p), m(yi + 1, p), s);
  return a + (b - a) * w(fx) + (c - a) * w(fy) + (a - b - c + d) * w(fx) * w(fy); }
function grassC(seed) { const N = 32, im = new Img(N, N, ix('grass', 3));
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) { const n = vnoise(x / 8, y / 8, 4, seed) * 0.65 + vnoise(x / 4, y / 4, 8, seed + 1) * 0.35; im.set(x, y, ix('grass', n < 0.36 ? 2 : 3)); }
  // blade tufts: a lit tip with a darker root below-right, placed on a jittered grid (no isolated noise)
  for (let gy = 0; gy < 6; gy++) for (let gx = 0; gx < 6; gx++) { if (hash(gx, gy, seed + 5) < 0.3) continue; const x = (gx * 5 + ((hash(gx, gy, seed + 2) * 5) | 0) + (gy & 1) * 2) % N, y = (gy * 5 + ((hash(gx, gy, seed + 3) * 5) | 0)) % N, k = hash(gx, gy, seed + 4);
    im.set(x, y, ix('grass', 4)); im.set(x, (y + 1) % N, ix('grass', 4)); if (k > 0.5) im.set((x + 1) % N, (y + N - 1) % N, ix('grass', 4)); im.set((x + 1) % N, (y + 1) % N, ix('grass', 2)); if (k > 0.75) im.set((x + N - 1) % N, (y + 1) % N, ix('grass', 4)); }
  return im; }
